fn set(s: &mut Store, which: usize) -> Result {
    let at = now();
    let snap = s.read().snapshot()?;
    let project = |id| snap.projects.iter().find(|p| p.id == id).cloned();
    let heading = |id| snap.headings.iter().find(|h| h.id == id).cloned();
    s.write(|w| {
        match which {
            1 | 2 | 9 => {
                let id = if which == 9 { DACHA } else { REPAIR };
                if let Some(mut p) = project(id) {
                    p.status = if which == 2 {
                        Status::Canceled { at }
                    } else {
                        Status::Completed { at }
                    };
                    w.update_project(&p)?;
                }
            }
            3 => w.delete(RecordId::Project(REPAIR), at)?,
            4 => w.delete(RecordId::Area(HOME), at)?,
            5 | 7 => {
                if let Some(mut h) = heading(if which == 5 { KITCHEN } else { BATH }) {
                    h.archived = true;
                    w.update_heading(&h)?;
                }
            }
            6 => w.delete(RecordId::Heading(KITCHEN), at)?,
            8 => w.delete(RecordId::Heading(BATH), at)?,
            10 => w.delete(RecordId::Area(GARDEN), at)?,
            11 => w.delete(RecordId::Tag(URGENT), at)?,
            12..=17 => {
                if which <= 15
                    && let Some(mut h) = heading(KITCHEN)
                {
                    h.archived = true;
                    w.update_heading(&h)?;
                }
                let extra: &[HeadingId] = if which == 14 || which == 15 {
                    &[KITCHEN2, KITCHEN3]
                } else {
                    &[KITCHEN2]
                };
                for &id in extra {
                    w.insert_heading(&Heading::new(id, REPAIR, "Кухня", Rank::initial(), at))?;
                }
                if which % 2 == 1
                    && let Some(mut p) = project(REPAIR)
                {
                    p.status = Status::Completed { at };
                    w.update_project(&p)?;
                }
            }
            _ => {}
        }
        Ok(())
    })?;
    Ok(())
}

fn moving(task: TaskId, m: MoveTask) -> Command {
    Command::MoveTask(MoveTask {
        task: task.to_string(),
        ..m
    })
}

/// Команда в записи командной строки: «move Плитка --heading Ванная»,
/// «done Плитка», «cancel Плитка», «add -p Ремонт -t Срочно», «project Баня
/// -a Дом», «heading Чердак -p Ремонт», «area Работа». Задачи – по UUID.
fn parse(line: &str) -> Command {
    let words: Vec<&str> = line.split_whitespace().collect();
    let task = |w: &str| match w {
        "Плитка" => TILE.to_string(),
        _ => LETTER.to_string(),
    };
    let flag = |name: &str| {
        words
            .iter()
            .position(|w| *w == name)
            .and_then(|i| words.get(i + 1))
            .map(|w| (*w).to_owned())
    };
    let has = |name: &str| words.contains(&name);
    match words[0] {
        "move" => Command::MoveTask(MoveTask {
            task: task(words[1]),
            when: flag("-w"),
            inbox: has("--inbox"),
            project: flag("-p"),
            heading: flag("--heading"),
            area: flag("-a"),
            no_project: has("--no-project"),
            deadline: flag("-d"),
            no_deadline: has("--no-deadline"),
        }),
        "done" | "cancel" => Command::Close(Close {
            tasks: vec![task(words[1])],
            cancel: words[0] == "cancel",
        }),
        "add" => Command::AddTask(NewTask {
            text: "Шпатель".into(),
            project: flag("-p"),
            heading: flag("--heading"),
            area: flag("-a"),
            tags: flag("-t").into_iter().collect(),
            ..NewTask::default()
        }),
        "project" => Command::AddProject(NewProject {
            title: words[1].into(),
            area: flag("-a"),
        }),
        "heading" => Command::AddHeading(NewHeading {
            title: words[1].into(),
            project: flag("-p").unwrap_or_default(),
        }),
        _ => Command::AddArea(NewArea {
            title: words[1].into(),
        }),
    }
}

