//! Команда ставит новую ссылку только на живое – по той же проверке цепочки,
//! что у отмены и повтора, – поэтому любую успешную команду можно сразу
//! отменить и повторить.

use jiff::Timestamp;
use jiff::civil::{Date, date};
use tally_app::{
    Clock, Close, Command, Effect, Error, MoveTask, NewArea, NewHeading, NewProject, NewTask,
    execute,
};
use tally_core::{
    Area, AreaId, Heading, HeadingId, Project, ProjectId, Rank, Start, Status, Tag, TagId, Task,
    TaskId,
};
use tally_store::{HistoryEntry, RecordId, Snapshot, Store};

type Result<T = ()> = std::result::Result<T, Box<dyn std::error::Error>>;

const TODAY: Date = date(2026, 11, 19);
const HOME: AreaId = AreaId::from_u128(1);
const GARDEN: AreaId = AreaId::from_u128(2);
const REPAIR: ProjectId = ProjectId::from_u128(3);
const DACHA: ProjectId = ProjectId::from_u128(4);
const KITCHEN: HeadingId = HeadingId::from_u128(5);
const BATH: HeadingId = HeadingId::from_u128(6);
const URGENT: TagId = TagId::from_u128(7);
const TILE: TaskId = TaskId::from_u128(8);
const LETTER: TaskId = TaskId::from_u128(9);
const KITCHEN2: HeadingId = HeadingId::from_u128(10);
const KITCHEN3: HeadingId = HeadingId::from_u128(11);

fn now() -> Timestamp {
    "2026-11-19T12:00:00Z"
        .parse()
        .unwrap_or(Timestamp::UNIX_EPOCH)
}

fn run(s: &mut Store, c: &Command) -> tally_app::Result<Effect> {
    let clock = Clock {
        today: TODAY,
        now: now(),
    };
    execute(s, c, clock).map(|d| d.effect)
}

fn state(s: &Store) -> Result<(Snapshot, Vec<HistoryEntry>)> {
    Ok((s.read().snapshot()?, s.read().history()?))
}

/// Область «Дом» с проектом «Ремонт» (разделы «Кухня» и «Ванная»), проект
/// «Дача», область «Сад», тег «Срочно»; «Плитка» – в «Ремонте / Кухне» с
/// тегом, «Письмо» – во «Входящих».
fn base() -> Result<Store> {
    let at = Timestamp::UNIX_EPOCH;
    let mut s = Store::open_in_memory()?;
    let mut repair = Project::new(REPAIR, "Ремонт", Rank::initial(), at);
    repair.area = Some(HOME);
    let mut tile = Task::new(TILE, "Плитка", Rank::initial(), at);
    tile.start = Start::Anytime;
    tile.project = Some(REPAIR);
    tile.heading = Some(KITCHEN);
    tile.tags = vec![URGENT];
    s.write(|w| {
        w.insert_area(&Area::new(HOME, "Дом", Rank::initial(), at))?;
        w.insert_area(&Area::new(GARDEN, "Сад", Rank::initial(), at))?;
        w.insert_tag(&Tag::new(URGENT, "Срочно", Rank::initial(), at))?;
        w.insert_project(&repair)?;
        w.insert_project(&Project::new(DACHA, "Дача", Rank::initial(), at))?;
        for (id, title) in [(KITCHEN, "Кухня"), (BATH, "Ванная")] {
            w.insert_heading(&Heading::new(id, REPAIR, title, Rank::initial(), at))?;
        }
        w.insert_task(&tile)?;
        w.insert_task(&Task::new(LETTER, "Письмо", Rank::initial(), at))
    })?;
    Ok(s)
}

