/// Снимок без времени правки (записей и пунктов чек-листа): его отмена и
/// повтор двигают вперёд.
fn content(s: &Snapshot) -> Snapshot {
    let mut s = s.clone();
    let epoch = Timestamp::UNIX_EPOCH;
    s.areas.iter_mut().for_each(|x| x.sync.updated_at = epoch);
    s.tags.iter_mut().for_each(|x| x.sync.updated_at = epoch);
    s.projects
        .iter_mut()
        .for_each(|x| x.sync.updated_at = epoch);
    s.headings
        .iter_mut()
        .for_each(|x| x.sync.updated_at = epoch);
    for t in &mut s.tasks {
        t.sync.updated_at = epoch;
        t.checklist
            .iter_mut()
            .for_each(|i| i.sync.updated_at = epoch);
    }
    s
}

/// Каждая пара «состояние × команда» даёт ровно ожидаемый исход. Отказ и
/// успех без изменений ничего не пишут; изменение сразу отменяется
/// (база – как до команды), повторяется (как после неё), снова отменяется и
/// повторяется.
#[test]
fn every_command_in_every_state_has_the_expected_outcome() -> Result {
    let mut actual = String::new();
    let mut ok = true;
    for (line, expected) in EXPECT {
        let mut row = Vec::new();
        for (which, name) in STATES.iter().enumerate() {
            let c = parse(line);
            let mut s = base()?;
            set(&mut s, which)?;
            let before = state(&s)?;
            let outcome = match run(&mut s, &c) {
                Err(Error::Rejected(why)) => {
                    assert_eq!(state(&s)?, before, "{name}, {line}");
                    why
                }
                Err(e) => format!("ошибка {e:?}"),
                Ok(_) if state(&s)? == before => "=".to_owned(),
                Ok(_) => {
                    let after = content(&s.read().snapshot()?);
                    for (step, want) in [
                        (Command::Undo, &before.0),
                        (Command::Redo, &after),
                        (Command::Undo, &before.0),
                        (Command::Redo, &after),
                    ] {
                        let r = run(&mut s, &step);
                        assert!(r.is_ok(), "{name}, {line}, {step:?}: {r:?}");
                        assert_eq!(
                            content(&s.read().snapshot()?),
                            content(want),
                            "{name}, {line}, {step:?}"
                        );
                    }
                    "+".to_owned()
                }
            };
            ok &= expected[which] == outcome;
            row.push(format!("{outcome:?}"));
        }
        actual.push_str(&format!(
            "    (\n        {line:?},\n        [{}],\n    ),\n",
            row.join(", ")
        ));
    }
    assert!(ok && EXPECT.len() == 34, "фактически:\n{actual}");
    Ok(())
}

fn refused(which: usize, c: &Command, message: &str) -> Result {
    let mut s = base()?;
    set(&mut s, which)?;
    let before = state(&s)?;
    let r = run(&mut s, c);
    assert!(matches!(&r, Err(Error::Rejected(_))), "{r:?}");
    assert_eq!(r.map_err(|e| e.to_string()), Err(message.to_owned()));
    assert_eq!(state(&s)?, before);
    Ok(())
}

