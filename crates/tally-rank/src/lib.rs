//! Строковые ключи порядка для списков: между любыми двумя ключами всегда
//! можно вставить новый, не трогая соседей.
//!
//! Ключ – ASCII-строка из алфавита base-62 (`0-9A-Za-z`). Порядок ключей –
//! обычное побайтовое сравнение строк, поэтому `ORDER BY` по колонке `TEXT`
//! в SQLite (сравнение `BINARY`) сортирует так же, как [`Rank`] в Rust.
//!
//! Схема – дробная индексация (как в `fractional-indexing` Д. Гринспена):
//! ключ = целая часть переменной длины + дробная часть.
//! - вставка в конец или в начало меняет целую часть, длина растёт
//!   логарифмически (тысячи вставок – 3–4 символа);
//! - вставка между соседями делит дробную часть пополам, длина растёт
//!   примерно на символ за ~6 вставок в одно и то же место;
//!   для таких случаев есть [`Rank::spread`] – ребалансировка списка.

