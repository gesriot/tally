#[test]
fn weekend_and_next_week_on_other_days() {
    let sat = date(2026, 11, 21);
    let sun = date(2026, 11, 22);
    let mon = date(2026, 11, 23);
    let day = |w: When| w.date();
    // В выходные «на выходных» – сегодня.
    assert_eq!(parse("на выходных", sat).ok().and_then(day), Some(sat));
    assert_eq!(parse("на выходных", sun).ok().and_then(day), Some(sun));
    // В воскресенье «следующий пн» – завтра, как и просто «пн».
    assert_eq!(parse("следующий пн", sun).ok().and_then(day), Some(mon));
    assert_eq!(parse("пн", sun).ok().and_then(day), Some(mon));
    // В понедельник «вт» – завтра, «следующий вт» – через неделю с днём.
    assert_eq!(
        parse("вт", mon).ok().and_then(day),
        Some(date(2026, 11, 24))
    );
    assert_eq!(
        parse("следующий вт", mon).ok().and_then(day),
        Some(date(2026, 12, 1))
    );
    // Месяц вперёд с 31-го – последний день короткого месяца.
    assert_eq!(
        parse("через месяц", date(2027, 1, 31)).ok().and_then(day),
        Some(date(2027, 2, 28))
    );
}

