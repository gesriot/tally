const TODAY: Date = date(2026, 11, 19); // четверг

fn on(m: i8, d: i8) -> When {
    When::On {
        date: date(2026, m, d),
        evening: false,
    }
}

fn eve(m: i8, d: i8) -> When {
    When::On {
        date: date(2026, m, d),
        evening: true,
    }
}

fn on_year(y: i16, m: i8, d: i8) -> When {
    When::On {
        date: date(y, m, d),
        evening: false,
    }
}

