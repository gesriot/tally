/// Пределы дат: `MIN_DATE` и `MAX_DATE` пишутся и читаются обратно, день
/// за пределами не пишется и не читается.
#[test]
fn date_range_boundaries() {
    assert_eq!(MIN_DATE, date(1000, 1, 1));
    assert_eq!(MAX_DATE, date(9999, 12, 31));
    let day = |d: Date| When::On {
        date: d,
        evening: false,
    };
    for today in [
        TODAY,
        MIN_DATE,
        MAX_DATE,
        date(1000, 6, 1),
        date(9999, 6, 1),
    ] {
        for d in [MIN_DATE, MAX_DATE] {
            for w in [
                day(d),
                When::On {
                    date: d,
                    evening: true,
                },
            ] {
                let text = format(w, today);
                assert!(text.is_some(), "{w:?} от {today}");
                let text = text.unwrap_or_default();
                assert_eq!(parse(&text, today), Ok(w), "«{text}» от {today}");
            }
        }
    }
    assert_eq!(
        format(day(date(1000, 1, 1)), TODAY).as_deref(),
        Some("1 января 1000")
    );
    assert_eq!(
        format(day(date(9999, 12, 31)), TODAY).as_deref(),
        Some("31 декабря 9999")
    );

    // Сразу за нижним пределом: не пишется, не читается.
    let before = date(999, 12, 31);
    assert_eq!(format(day(before), TODAY), None);
    assert_eq!(format(day(date(999, 1, 1)), TODAY), None);
    assert_eq!(format(day(before), before), None);
    assert_eq!(
        parse("1 января 999", TODAY),
        Err(ParseError::Unknown("1 января 999".into()))
    );
    assert_eq!(parse("31 декабря 0999", TODAY), Err(ParseError::OutOfRange));
    assert_eq!(parse("31.12.0999", TODAY), Err(ParseError::OutOfRange));
    assert_eq!(parse("сегодня", before), Err(ParseError::OutOfRange));
    assert_eq!(parse("вечером", before), Err(ParseError::OutOfRange));
    assert_eq!(parse("завтра", before), Ok(day(MIN_DATE)));
    assert_eq!(parse("1 января", before), Ok(day(MIN_DATE)));
    // Сразу за верхним пределом.
    assert_eq!(parse("завтра", MAX_DATE), Err(ParseError::OutOfRange));
    assert_eq!(
        parse("через неделю", date(9999, 12, 30)),
        Err(ParseError::OutOfRange)
    );
    assert_eq!(
        parse("через месяц", date(9999, 12, 1)),
        Err(ParseError::OutOfRange)
    );
    assert_eq!(parse("в пятницу", MAX_DATE), Err(ParseError::OutOfRange));
    assert_eq!(parse("сегодня", MAX_DATE), Ok(day(MAX_DATE)));
    assert_eq!(parse("1 января", MAX_DATE), Err(ParseError::OutOfRange));
    assert_eq!(parse("31.12", MAX_DATE), Ok(day(MAX_DATE)));
}

#[test]
fn when_maps_onto_core_fields() {
    let mut t = tally_core::Task::new(
        tally_core::TaskId::from_u128(1),
        "Купить хлеб",
        tally_core::Rank::initial(),
        tally_core::Timestamp::UNIX_EPOCH,
    );
    t.deadline = Some(date(2026, 12, 1));
    let at: tally_core::Timestamp = "2026-11-19T09:00:00Z"
        .parse()
        .unwrap_or(tally_core::Timestamp::UNIX_EPOCH);
    eve(11, 20).apply_to_task(&mut t, at);
    assert_eq!(
        (t.start, t.date, t.evening, t.deadline, t.sync.updated_at),
        (
            Start::Anytime,
            Some(date(2026, 11, 20)),
            true,
            Some(date(2026, 12, 1)),
            at
        )
    );
    When::Someday.apply_to_task(&mut t, at);
    assert_eq!((t.start, t.date, t.evening), (Start::Someday, None, false));
    When::Anytime.apply_to_task(&mut t, at);
    assert_eq!((t.start, t.date, t.evening), (Start::Anytime, None, false));

    // Задача с датой из разбора попадает в нужный список tally-core.
    on(11, 19).apply_to_task(&mut t, at);
    assert_eq!(
        tally_core::lists::list_of(&t, None, None, None, TODAY),
        tally_core::lists::List::Today { evening: false }
    );

    let mut p = tally_core::Project::new(
        tally_core::ProjectId::from_u128(1),
        "Ремонт",
        tally_core::Rank::initial(),
        at,
    );
    on(12, 15).apply_to_project(&mut p, at);
    assert_eq!(
        (p.start, p.date),
        (Start::Anytime, Some(date(2026, 12, 15)))
    );
}
