/// Время быстрого ввода на длинных названиях.
fn speed(today: Date) {
    println!("\nБыстрый ввод на длинных названиях\n");
    for n in [10_000usize, 100_000] {
        let rep = |w: &str| vec![w; n].join(" ");
        let plain = (0..n)
            .map(|i| format!("слово{i}"))
            .collect::<Vec<_>>()
            .join(" ");
        let mix = [
            "в",
            "через",
            "сто",
            "с",
            "половиной",
            "дней",
            "назад",
            "вечером",
            "15",
            "декабря",
        ];
        let cases = [
            ("обычные слова", plain.clone()),
            ("обычные слова + «завтра»", format!("{plain} завтра")),
            (
                "вводные «в» + «через 3 дня»",
                format!("Позвонить {} через 3 дня", rep("в")),
            ),
            (
                "«сто» подряд + «с часа завтра»",
                format!("Тренировка {} с часа завтра", rep("сто")),
            ),
            (
                "«сто» подряд + «часа завтра»",
                format!("Тренировка {} часа завтра", rep("сто")),
            ),
            ("«через» подряд", rep("через")),
            (
                "«через» подряд + «завтра»",
                format!("Купить {} завтра", rep("через")),
            ),
            (
                "«15» подряд + «дней назад»",
                format!("{} дней назад", rep("15")),
            ),
            (
                "через + «сто» подряд + «дней вечером»",
                format!("Напомнить через {} дней вечером", rep("сто")),
            ),
            (
                "через + «сто» подряд + «дней завтра»",
                format!("Напомнить через {} дней завтра", rep("сто")),
            ),
            (
                "смесь слов даты",
                (0..n)
                    .map(|i| mix[i % mix.len()])
                    .collect::<Vec<_>>()
                    .join(" "),
            ),
        ];
        for (name, text) in &cases {
            let start = std::time::Instant::now();
            let q = split_title(text, today);
            let ms = start.elapsed().as_secs_f64() * 1000.0;
            let when = if q.when.is_some() {
                "дата"
            } else {
                "без даты"
            };
            println!("{n:>7} слов, {name:<40} {ms:>9.2} мс, {when}");
        }
    }
}
