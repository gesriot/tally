const WEEKDAYS: [&str; 7] = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"];

fn show_date(d: Date) -> String {
    let wd = WEEKDAYS
        .get(usize::try_from(d.weekday().to_monday_zero_offset()).unwrap_or(0))
        .copied()
        .unwrap_or("");
    const MONTHS: [&str; 12] = [
        "января",
        "февраля",
        "марта",
        "апреля",
        "мая",
        "июня",
        "июля",
        "августа",
        "сентября",
        "октября",
        "ноября",
        "декабря",
    ];
    let month = MONTHS
        .get(usize::try_from(d.month() - 1).unwrap_or(0))
        .copied()
        .unwrap_or("");
    format!("{wd}, {} {month} {}", d.day(), d.year())
}

fn show(when: When) -> String {
    match when {
        When::On { date, evening } => {
            let mut s = show_date(date);
            if evening {
                s.push_str(", вечер");
            }
            s
        }
        When::Anytime => "в любое время".to_owned(),
        When::Someday => "когда-нибудь".to_owned(),
    }
}

