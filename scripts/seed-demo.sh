#!/bin/sh
# Демо-база для окна Tally: области «Дом» и «Работа», проект «Ремонт» с
# разделами, задачи на сегодня, вечер, со сроками и во «Входящих».
#
#   scripts/seed-demo.sh /tmp/demo.db           # создать базу
#   TALLY_TODAY=2026-11-20 tally-ui --db /tmp/demo.db
#
# Даты считаются от 20 ноября 2026 (пятница). Нужен собранный `tally`
# (cargo build -p tally-cli), запускать из корня репозитория – путь к `tally`
# можно задать в TALLY.
set -eu
DB=${1:?укажите путь к новой базе}
TALLY=${TALLY:-target/debug/tally}
rm -f "$DB"
t() { TALLY_DB="$DB" TALLY_TODAY=${DAY:-2026-11-20} "$TALLY" "$@" >/dev/null; }

t area Дом
t area Работа
t project Ремонт -a Дом
t heading Кухня -p Ремонт
t heading Ванная -p Ремонт
t project Дача -a Дом
t project "Годовой отчёт" -a Работа
t project "Поездка в Казань"

t add "Записаться к стоматологу"
t add "Идея: курс по Rust" -t идеи
t add "Посмотреть «Солярис»" -w "в любое время"

t add "Купить плитку" -p Ремонт --heading Кухня -w сегодня -d пн
t add "Выбрать краску для стен" -p Ремонт --heading Кухня
t add "Заказать смеситель" -p Ремонт --heading Ванная -w завтра
t add "Позвонить электрику" -p Ремонт -w сегодня
t add "Вывезти мусор" -p Ремонт --heading Ванная -w когда-нибудь
t add "Оплатить интернет" -a Дом -w сегодня -d сегодня -t счета
t add "Подготовить слайды" -p "Годовой отчёт" -w сегодня -t работа
t add "Собрать цифры продаж" -p "Годовой отчёт" -d "через 2 недели"
t add "Прочитать главу книги" -w вечером
t add "Позвонить маме" -w "сегодня вечером"
t add "Купить билеты на поезд" -p "Поездка в Казань" -w "15 дек"
t add "Полить рассаду" -p Дача -w пн
# Срок уже прошёл: задача добавлена «во вторник» со сроком в среду.
DAY=2026-11-17 t add "Сдать показания счётчиков" -a Дом -d ср
t add "Отправить договор" -a Работа
t done "Отправить договор"
